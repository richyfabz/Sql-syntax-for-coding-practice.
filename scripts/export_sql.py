"""Export notebook SQL cells into psql scripts using only the Python standard library."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
output = root / 'sql' / 'notebooks'
output.mkdir(exist_ok=True)
for path in sorted(root.glob('*.ipynb')):
    notebook = json.loads(path.read_text())
    statements = ['-- Generated by scripts/export_sql.py; edit the notebook, then regenerate.\n',
                  '\\set ON_ERROR_STOP on\nSET search_path TO sql_practice, public;\n']
    for index, cell in enumerate(notebook['cells']):
        if cell['cell_type'] == 'code':
            source = ''.join(cell['source'])
            assert source.lstrip().startswith('--'), (path, index)
            statements.append(f'\n-- Notebook cell {index}\n{source}\n')
    (output / (path.stem + '.sql')).write_text(''.join(statements))
    print(f'Exported {path.name}')
